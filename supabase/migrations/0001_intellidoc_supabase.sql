-- IntelliDoc AI: Supabase schema
-- Run in Supabase Dashboard -> SQL Editor.
create extension if not exists vector with schema extensions;

create table if not exists public.documents (
    id uuid primary key,
    filename text not null,
    storage_path text,
    file_size bigint not null,
    page_count integer not null,
    extracted_chars integer not null,
    uploaded_at timestamptz not null default now()
);

create table if not exists public.document_chunks (
    id bigint generated by default as identity primary key,
    document_id uuid not null references public.documents(id) on delete cascade,
    page_number integer not null,
    chunk_index integer not null,
    content text not null,
    embedding extensions.vector(384) not null,
    unique (document_id, page_number, chunk_index)
);

-- Compatibility for projects where the initial schema was already run.
alter table public.documents add column if not exists storage_path text;
alter table public.documents alter column storage_path drop not null;
create unique index if not exists document_chunks_doc_page_chunk_uidx
    on public.document_chunks(document_id, page_number, chunk_index);

create index if not exists document_chunks_document_idx
    on public.document_chunks(document_id);

create index if not exists document_chunks_embedding_idx
    on public.document_chunks
    using hnsw (embedding extensions.vector_cosine_ops);

create table if not exists public.chat_sessions (
    id uuid primary key,
    title text not null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.chat_messages (
    id bigint generated by default as identity primary key,
    chat_id uuid not null references public.chat_sessions(id) on delete cascade,
    role text not null check (role in ('user', 'assistant')),
    content text not null,
    created_at timestamptz not null default now()
);

create index if not exists chat_messages_chat_idx
    on public.chat_messages(chat_id, id);

