drop function if exists public.match_document_chunks(extensions.vector, integer);

create function public.match_document_chunks(
    query_embedding extensions.vector(384),
    match_count integer default 5
)
returns table (
    document_id uuid,
    filename text,
    page_number integer,
    chunk_index integer,
    content text,
    similarity double precision
)
language sql
stable
set search_path = public, extensions
as $$
    select
        dc.document_id,
        d.filename,
        dc.page_number,
        dc.chunk_index,
        dc.content,
        1 - (dc.embedding <=> query_embedding) as similarity
    from public.document_chunks as dc
    join public.documents as d on d.id = dc.document_id
    order by dc.embedding <=> query_embedding
    limit greatest(1, least(coalesce(match_count, 5), 20));
$$;

grant execute on function public.match_document_chunks(extensions.vector, integer)
to service_role;
